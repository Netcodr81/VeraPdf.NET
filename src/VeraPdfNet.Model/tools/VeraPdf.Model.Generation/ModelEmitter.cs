using System.Security;
using System.Text;
using System.Text.Json;

namespace VeraPdf.Model.Generation;

public static class ModelEmitter
{
    public const string Banner = "// <auto-generated by VeraPdf.Model.Generation>";
    public const string GeneratorCommit = "f8e9f87d98a96784cd78a15229736722bb77eff8";

    public static IReadOnlyDictionary<string, string> Emit(IReadOnlyList<ModelEntity> entities)
    {
        ModelSchema.Validate(entities);
        var output = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var group in entities.GroupBy(e => ModelSchema.Namespace(e.Package)).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var code = new StringBuilder();
            code.AppendLine(Banner);
            code.AppendLine("// SPDX-License-Identifier: GPL-3.0-or-later OR MPL-2.0");
            code.AppendLine("// Derived from veraPDF model declarations; regenerate, do not edit.");
            code.AppendLine("#nullable enable");
            code.AppendLine($"namespace {group.Key};");
            foreach (var entity in group.OrderBy(e => e.Name, StringComparer.Ordinal))
            {
                code.AppendLine();
                Summary(code, entity.Documentation, $"Validation contract for {entity.Name}.");
                code.AppendLine($"/// <remarks>Source: {entity.Source}; Java: {entity.JavaName}.");
                foreach (var link in entity.Links)
                {
                    code.AppendLine($"/// Link {link.Name}: {link.Type}{link.Multiplicity}, accessed through GetLinkedObjects.");
                    foreach (var comment in link.Documentation)
                    {
                        code.AppendLine(("/// " + SecurityElement.Escape(comment)).TrimEnd());
                    }
                }
                code.AppendLine("/// </remarks>");
                var inheritance = entity.BaseName is null ? "" :
                    " : global::" + ModelSchema.Resolve(entity, entity.BaseName, entities).ClrName;
                code.AppendLine($"public interface {entity.ClrName.Split('.')[^1]}{inheritance}");
                code.AppendLine("{");
                if (entity.BaseName is null)
                {
                    foreach (var method in RootMethods)
                    {
                        code.AppendLine($"    /// <summary>{method.Description}</summary>");
                        code.AppendLine($"    {method.Signature};");
                    }
                }
                foreach (var property in entity.Properties)
                {
                    Summary(code, property.Documentation, $"Gets the {property.Name} validation fact.", "    ");
                    code.AppendLine($"    /// <remarks>DSL {SecurityElement.Escape(property.Type)}; may be absent or invalid. Java getter: get{property.Name}.</remarks>");
                    code.AppendLine($"    {ModelSchema.ScalarType(property.Type)} Get{property.Name}();");
                }
                code.AppendLine("}");
            }
            var layer = group.Key.Split('.')[^1];
            output.Add(layer + ".g.cs", Normalize(code.ToString()));
        }
        var manifest = entities.OrderBy(e => e.JavaName, StringComparer.Ordinal).Select(e => new
        {
            e.Name,
            e.JavaName,
            e.ClrName,
            Source = e.Source,
            BaseName = e.BaseName is null ? null : ModelSchema.Resolve(e, e.BaseName, entities).Name,
            Properties = e.Properties.Select(p => new { p.Name, DslType = p.Type, ClrType = ModelSchema.ScalarType(p.Type) }),
            Links = e.Links.Select(l => new
            {
                l.Name,
                Target = ModelSchema.Resolve(e, l.Type, entities).Name,
                Multiplicity = l.Multiplicity
            })
        });
        output.Add("schema.json", Normalize(JsonSerializer.Serialize(new
        {
            GeneratorCommit,
            Types = manifest
        }, new JsonSerializerOptions { WriteIndented = true })) + "\n");
        return output;
    }

    private static readonly (string Signature, string Description)[] RootMethods =
    [
        ("IReadOnlyList<string> GetLinks()", "Gets link names, including inherited names, in model declaration order."),
        ("IReadOnlyList<IModelObject> GetLinkedObjects(string linkName)", "Gets linked model objects by exact, case-sensitive name. Unsupported access must fail explicitly."),
        ("IReadOnlyList<string> GetSuperTypes()", "Gets ancestor model names, nearest ancestor first."),
        ("IReadOnlyList<string> GetProperties()", "Gets property names, including inherited names, in model declaration order."),
        ("string GetObjectType()", "Gets the original simple model type name, not the C# interface name."),
        ("string? GetID()", "Gets an optional producer-defined identity, distinct from CLR object identity."),
        ("bool? IsContextDependent()", "Reports context dependence; null means it is not yet known."),
        ("string? GetExtraContext()", "Gets optional producer-defined extra validation context."),
        ("string? GetContext()", "Gets optional producer-defined validation context.")
    ];

    private static void Summary(StringBuilder code, IReadOnlyList<string> documentation, string fallback, string indent = "")
    {
        code.AppendLine(indent + "/// <summary>");
        if (documentation.Count == 0) code.AppendLine(indent + "/// " + fallback);
        foreach (var line in documentation) code.AppendLine((indent + "/// " + SecurityElement.Escape(line)).TrimEnd());
        code.AppendLine(indent + "/// </summary>");
    }

    private static string Normalize(string value) => value.Replace("\r\n", "\n", StringComparison.Ordinal);
}
